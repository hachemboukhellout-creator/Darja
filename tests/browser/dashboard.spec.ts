import {test,expect} from '@playwright/test';

test('order workflow persists from creation through delivery, customer and search',async({page})=>{
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Let’s make good things happen.'})).toBeVisible();
  await page.getByRole('button',{name:'Create order',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Customer name').fill('Nadia Browser');
  await dialog.getByLabel('Phone number').fill('0550998877');
  await dialog.getByLabel('Email').fill('nadia@example.com');
  await dialog.getByLabel('Wilaya',{exact:true}).selectOption('Alger');
  await dialog.getByLabel('Delivery address').fill('18 rue Didouche Mourad');
  await dialog.getByLabel('Product',{exact:true}).fill('Browser test linen tote');
  await dialog.getByLabel('Order total').fill('4250.50');
  await dialog.getByRole('button',{name:'Create order',exact:true}).click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button',{name:'Orders',exact:true}).click();
  await page.getByLabel('Search orders').fill('Nadia Browser');
  await expect(page.getByText('Nadia Browser',{exact:true})).toBeVisible();
  await page.getByText('Nadia Browser',{exact:true}).click();
  await expect(dialog.getByText('4,250.5',{exact:false})).toBeVisible();
  await dialog.getByRole('button',{name:'Confirm order',exact:true}).click();
  await expect(dialog.getByRole('button',{name:'Mark as shipped'})).toBeVisible();
  await dialog.getByRole('button',{name:'Mark as shipped'}).click();
  await expect(dialog.getByRole('button',{name:'Mark as delivered'})).toBeVisible();
  await dialog.getByRole('button',{name:'Mark as delivered'}).click();
  await expect(dialog.locator('.detail-status')).toContainText('Delivered');
  await dialog.getByRole('button',{name:'Close dialog'}).click();
  await page.reload();
  await page.getByRole('button',{name:'Customers',exact:true}).click();
  await page.getByLabel('Search customers').fill('Nadia Browser');
  await expect(page.getByText('Nadia Browser',{exact:true})).toBeVisible();
  await expect(page.locator('tbody')).toContainText('4,250.5');
  await page.getByRole('button',{name:'View Nadia Browser\'s orders'}).click();
  await expect(page.locator('tbody')).toContainText('Delivered');
});

test('registration starts empty, settings persist and secure sign-in works',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Create your workspace',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByRole('button',{name:'Create account',exact:true}).click();
  const email=`browser-${Date.now()}-${Math.random().toString(36).slice(2)}@example.com`;
  await dialog.getByLabel('Your full name').fill('Amine Tester');
  await dialog.getByLabel('Store name').fill('Atelier Test');
  await dialog.getByLabel('Email address').fill(email);
  await dialog.getByLabel('Password').fill('Browser-secure-password-2026');
  await dialog.getByRole('button',{name:'Create workspace',exact:true}).click();
  await expect(dialog).toBeHidden();
  await expect(page.getByText('Atelier Test',{exact:true})).toBeVisible();
  await expect(page.getByText('Nothing here just yet')).toBeVisible();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('Store name',{exact:true}).fill('Atelier Updated');
  await page.getByRole('button',{name:'Save changes'}).click();
  await expect(page.getByRole('status')).toHaveText(/Workspace settings saved/);
  await page.getByRole('button',{name:'Account menu'}).click();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password').fill('Browser-secure-password-2026');
  await page.getByRole('button',{name:'Sign in securely'}).click();
  await expect(page.getByText('Atelier Updated',{exact:true})).toBeVisible();
});

test('mobile navigation, analytics, and search fit a narrow viewport',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Let’s make good things happen.'})).toBeVisible();
  await expect(page.locator('.sidebar')).not.toBeInViewport();
  await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('button',{name:'COD confirmation',exact:false}).click();
  await expect(page.getByRole('heading',{name:'COD confirmation.'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Confirm',exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('button',{name:'Analytics',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Analytics.'})).toBeVisible();
  await page.getByLabel('Analytics date range').selectOption('7');
  await expect(page.getByRole('heading',{name:'Where your customers are'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
});
